// stubResolver returns a SchemaResolver that always answers with the supplied
// resource-type record. Build's dereferencer expects the nested `schema`
// shape; pass in the same fixture the old test used.
func stubResolver(rt map[string]any) bundle.SchemaResolver {
	return func(_ context.Context, _ string) (map[string]any, error) {
		return rt, nil
	}
}

func TestBuildTFVars(t *testing.T) {
	testDir := t.TempDir()
	if err := mockfilesystem.SetupBundle(testDir); err != nil {
		t.Fatal(err)
	}

	file, err := os.ReadFile(path.Join(testDir, "massdriver.yaml"))
	if err != nil {
		t.Fatal(err)
	}

	unmarshalledBundle := &bundle.Bundle{}
	if err := yaml.Unmarshal(file, unmarshalledBundle); err != nil {
		t.Fatal(err)
	}

	if err := unmarshalledBundle.Build(testDir, stubResolver(draftNodeSchema)); err != nil {
		t.Fatal(err)
	}

	for fileName, expectedContent := range expectedTFContent {
		gotContent, readFileErr := os.ReadFile(path.Join(testDir, "src", fileName))
		if readFileErr != nil {
			t.Fatal(readFileErr)
		}
		if string(gotContent) != string(expectedContent) {
			t.Errorf("Expected file content for %s to be %s but got %s", fileName, string(expectedContent), string(gotContent))
		}
	}
}

func TestBuildDependencyCardinality(t *testing.T) {
	queueSchema := map[string]any{
		"schema": map[string]any{
			"type":     "object",
			"required": []any{"arn"},
			"properties": map[string]any{
				"arn": map[string]any{"type": "string"},
			},
		},
	}

	cases := []struct {
		name        string
		cardinality string
		want        string
	}{
		{
			name: "one",
			want: `variable "queues" {
  type = object({
    arn = string
  })
}
`,
		},
		{
			name:        "many",
			cardinality: "    cardinality: many\n",
			want: `variable "queues" {
  type = map(object({
    arn = string
  }))
  default = {}
}
`,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := os.Mkdir(path.Join(dir, "src"), 0750); err != nil {
				t.Fatal(err)
			}
			massdriverYAML := "name: worker\ndescription: drains queues\nversion: 1.0.0\nsteps:\n  - path: src\n    provisioner: opentofu\nparams:\n  properties: {}\nui: {}\ndependencies:\n  queues:\n    resource_type: aws-sqs-queue@~2.0\n    required: true\n" + tc.cardinality
			if err := os.WriteFile(path.Join(dir, "massdriver.yaml"), []byte(massdriverYAML), 0600); err != nil {
				t.Fatal(err)
			}

			b, err := bundle.Unmarshal(dir)
			if err != nil {
				t.Fatal(err)
			}
			if buildErr := b.Build(dir, stubResolver(queueSchema)); buildErr != nil {
				t.Fatal(buildErr)
			}

			got, err := os.ReadFile(path.Join(dir, "src", "_massdriver_variables.tf"))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(got), tc.want) {
				t.Errorf("generated variables missing\n%s\ngot\n%s", tc.want, got)
			}
		})
	}
}
